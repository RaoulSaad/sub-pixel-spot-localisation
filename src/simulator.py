from dataclasses import dataclass, replace
from pathlib import Path

import tomllib
import warnings

import numpy as np
from numpy.typing import NDArray

from scipy.special import erf


FloatImage = NDArray[np.float64]
DigitalImage = NDArray[np.uint16]


def make_rngs(seed: int) -> tuple[np.random.Generator, np.random.Generator]:
    """Independent streams: one for the fixed camera sensor, one for per-frame noise."""
    sensor_seq, frame_seq = np.random.SeedSequence(seed).spawn(2)
    return np.random.default_rng(sensor_seq), np.random.default_rng(frame_seq)


@dataclass
class SpotConfig:
    # Default value for the coordinates of the center of the spot,
    # will be generated during runs
    center_xy: tuple[float, float] = (15.3, 14.7)

    # Default spot width in pixels (sigma = 1.75 gives 7 pixels)
    sigma_x: float = 1.75                           
    sigma_y: float = 1.75

    # Expected total spot electrons per exposure
    total_signal_e: float = 10_000.0


@dataclass
class CameraConfig:
    shape: tuple[int, int] = (32, 32)  # Simulation window - Enough room for spot and background noise
    exposure_s: float = 0.001          # Duration over which the camera collects light

    # Camera specs, will be loaded from config
    read_noise_e: float = 3.0
    dark_current_e_per_s: float = 50.0
    full_well_e: float = 10_000.0

    # Signal to Digital conversion settings (camera related)
    bit_depth: int = 12
    bias_dn: float = 100.0

    # Pixel sensitivity variantion and hot pixels
    prnu_std: float = 0.01
    hot_pixel_fraction: float = 0.001
    hot_pixel_dark_multiplier: float = 10000.0  # illustrative assumption

    # Conversion scale: electrons corresponding to a one-DN increase.
    # Assume full-well charge maps to the maximum code after adding bias.
    @property
    def electrons_per_dn(self) -> float:
        return self.full_well_e / (2**self.bit_depth - 1 - self.bias_dn)


@dataclass
class BackgroundConfig:
    # Expected detected electrons per pixel per exposure,
    # before applying the pixel sensitivity map,
    # defined at the center of the image.
    level_e: float = 10.0                   # Expected background signal
    gradient_x_e_per_px: float = 0.3        # Background change per pixel on the x-axis
    gradient_y_e_per_px: float = 0.2        # Background change per pixel on the y-axis

# Path to find the camera configs
CONFIG_DIR = Path(__file__).parent.parent / "configs"


def load_config(
    path: str | Path,
) -> tuple[CameraConfig, SpotConfig, BackgroundConfig]:
    """
    Load a camera preset from a TOML file with [camera], [spot] and
    [background] tables. A bare name such as "ingaas" resolves to
    configs/ingaas.toml. Missing keys keep the dataclass defaults;
    unknown keys raise TypeError.
    """
    path = Path(path)
    if not path.suffix:
        path = CONFIG_DIR / f"{path.name}.toml"

    with open(path, "rb") as f:
        data = tomllib.load(f)

    unknown = set(data) - {"camera", "spot", "background"}
    if unknown:
        raise ValueError(f"unknown config tables: {sorted(unknown)}")

    camera_kwargs = dict(data.get("camera", {}))
    if "shape" in camera_kwargs:
        camera_kwargs["shape"] = tuple(camera_kwargs["shape"])

    spot_kwargs = dict(data.get("spot", {}))
    if "center_xy" in spot_kwargs:
        spot_kwargs["center_xy"] = tuple(spot_kwargs["center_xy"])

    camera = CameraConfig(**camera_kwargs)
    spot = SpotConfig(**spot_kwargs)
    background = BackgroundConfig(**data.get("background", {}))

    validate_config(camera, spot, background)
    return camera, spot, background


@dataclass
class SensorMaps:
    """Generate once and reuse for frames from the same camera."""

    relative_sensitivity: FloatImage  # dimensionless, near 1 - pixel's sensitivity to light (PRNU)
    dark_current_e_per_s: FloatImage  # includes hot pixels - Dark current generated by the electrons in the camera & hot pixels


@dataclass
class SimulatedFrame:
    image_dn: DigitalImage                  # Digital Numbers of each pixel
    expected_spot_e: FloatImage             # Spot electrons
    expected_background_e: FloatImage       # Background electrons
    expected_dark_e: FloatImage             # Dark current electrons
    true_center_xy_px: tuple[float, float]  # Ground truth of spot center
    nominal_snr: float                      # SNR value
    n_saturated_pixels: int                 # Number of saturated pixels


def validate_config(camera, spot, background):
    """"
    Ensure values are within the correct range.
    """

    height, width = camera.shape
    if height <= 0 or width <= 0:
        raise ValueError("shape must be positive")
    if camera.exposure_s <= 0 or camera.full_well_e <= 0:
        raise ValueError("exposure and full well must be positive")
    if camera.read_noise_e < 0 or camera.dark_current_e_per_s < 0:
        raise ValueError("noise parameters must be non-negative")
    if not 1 <= camera.bit_depth <= 16:
        raise ValueError("bit_depth must be 1..16 (output is uint16)")
    if not 0 <= camera.bias_dn < 2**camera.bit_depth - 1:
        raise ValueError("bias_dn must fit inside the digital range")
    if spot.sigma_x <= 0 or spot.sigma_y <= 0 or spot.total_signal_e < 0:
        raise ValueError("spot sigma must be positive, signal non-negative")

    # Darkest corner of the background plane must not go below zero.
    min_background = (
        background.level_e
        - abs(background.gradient_x_e_per_px) * (width - 1) / 2
        - abs(background.gradient_y_e_per_px) * (height - 1) / 2
    )
    if min_background < 0:
        raise ValueError("background plane goes negative; reduce the gradient")



def make_sensor_maps(
    camera: CameraConfig,
    rng: np.random.Generator,
) -> SensorMaps:
    """
    Build a fixed positive sensitivity map with the requested PRNU.
    Build a dark-current map and assign elevated rates to hot pixels.
    """
    relative_sensitivity = 1.0 + camera.prnu_std * rng.standard_normal(camera.shape)

    dark_current = np.full(camera.shape, camera.dark_current_e_per_s, dtype=np.float64)
    hot = rng.random(camera.shape) < camera.hot_pixel_fraction
    dark_current[hot] *= camera.hot_pixel_dark_multiplier

    return SensorMaps(relative_sensitivity=relative_sensitivity, dark_current_e_per_s=dark_current)


def render_pixel_integrated_gaussian(
    shape: tuple[int, int],
    spot: SpotConfig,
) -> FloatImage:
    """
    Return expected spot electrons in each pixel.

    Convention:
      - Pixel centers have integer coordinates.
      - image[row, column] corresponds to (y, x).
      - Integrate over pixel areas using Gaussian CDF/erf differences.
      - total_signal_e refers to the Gaussian over the entire plane;
        light outside the image is lost.
    """
    height, width = shape

    
    edges_x = np.arange(width + 1) - 0.5
    edges_y = np.arange(height + 1) - 0.5

    cdf_x = 0.5 * (1 + erf((edges_x - spot.center_xy[0]) / (np.sqrt(2) * spot.sigma_x)))
    cdf_y = 0.5 * (1 + erf((edges_y - spot.center_xy[1]) / (np.sqrt(2) * spot.sigma_y)))

    frac_X = np.diff(cdf_x)
    frac_Y = np.diff(cdf_y)
    image = spot.total_signal_e * np.outer(frac_Y, frac_X)

    return image


def render_moving_spot(
    shape: tuple[int, int],
    spot: SpotConfig,
    path_xy: NDArray[np.float64],
) -> FloatImage:
    """
    Expected spot electrons when the spot moves during the exposure.

    `path_xy` holds the spot centre at equally spaced instants inside the
    exposure, shape (n, 2). The sensor integrates light over the exposure,
    so the expected image is the average of the spot rendered at each
    instant. This is motion blur: the image is slightly smeared along the
    path, and its centre of mass is the mean position over the exposure.
    """
    image = np.zeros(shape, dtype=np.float64)
    for x, y in path_xy:
        image += render_pixel_integrated_gaussian(shape, replace(spot, center_xy=(x, y)))
    return image / len(path_xy)


def render_background(
    shape: tuple[int, int],
    background: BackgroundConfig,
) -> FloatImage:
    """Return a nonnegative plane of expected background electrons.
    
    B(x, y) = level_e + gradient_x · (x - x_c) + gradient_y · (y - y_c)
    where (x_c, y_c) is the center of the image.
    level_e: float
    gradient_x_e_per_px: float
    gradient_y_e_per_px: float
    """
    height, width = shape
    ys, xs = np.indices(shape, dtype=np.float64)
    
    x_c = (width - 1) / 2
    y_c = (height - 1) / 2

    img = background.level_e + background.gradient_x_e_per_px * (xs - x_c) + background.gradient_y_e_per_px * (ys - y_c)

    return img


def apply_pixel_sensitivity(
    expected_image_e: FloatImage,
    sensor_maps: SensorMaps,
) -> FloatImage:
    """Multiply expected photoelectrons by the fixed sensitivity map."""
    return expected_image_e * sensor_maps.relative_sensitivity


def expected_dark_electrons(
    camera: CameraConfig,
    sensor_maps: SensorMaps,
) -> FloatImage:
    """Convert dark-current rates to expected counts for this exposure."""
    return sensor_maps.dark_current_e_per_s * camera.exposure_s

def sample_poisson_electrons(
    expected_e: FloatImage,
    rng: np.random.Generator,
) -> FloatImage:
    """Sample shot noise from the combined spot, background, and dark mean."""
    return rng.poisson(expected_e).astype(np.float64)


def apply_full_well_limit(
    collected_e: FloatImage,
    camera: CameraConfig,
) -> FloatImage:
    """Cap collected charge at full well. Blooming is ignored."""
    return np.minimum(collected_e, camera.full_well_e)


def add_read_noise(
    collected_e: FloatImage,
    camera: CameraConfig,
    rng: np.random.Generator,
) -> FloatImage:
    """Add zero-mean Gaussian noise in electrons. Preserve negative values."""
    return collected_e + rng.normal(loc=0.0, scale=camera.read_noise_e, size=collected_e.shape)


def digitize(
    measured_e: FloatImage,
    camera: CameraConfig,
) -> DigitalImage:
    """
    Convert electrons to DN, add bias, round, then clip to digital range.
    DN = digital number.
    """

    dn = measured_e / camera.electrons_per_dn + camera.bias_dn
    max_dn = 2**camera.bit_depth - 1

    return np.clip(np.round(dn), 0, max_dn).astype(np.uint16)


def calculate_nominal_snr(
    expected_spot_e: FloatImage,
    expected_background_e: FloatImage,
    expected_dark_e: FloatImage,
    read_noise_e: float,
    spot: SpotConfig,
) -> float:
    """
    Define SNR over the fixed aperture of the spot.

        SNR = S/sqrt(S + B + D + N*sigma_noise)

    Inputs are after sensitivity correction/application.
    Excludes quantization, saturation, and systematic estimation errors.
    Assumes background mean is known.
    """
    ys, xs = np.indices(expected_spot_e.shape)
    x0, y0 = spot.center_xy

    # Choose the pixels in the region around the spot
    aperture = (
        ((xs - x0) / (2 * spot.sigma_x)) ** 2
        + ((ys - y0) / (2 * spot.sigma_y)) ** 2
    ) <= 1.0

    signal = expected_spot_e[aperture].sum()
    variance = (
        signal
        + expected_background_e[aperture].sum()
        + expected_dark_e[aperture].sum()
        + aperture.sum() * read_noise_e**2
    )

    return float(signal / np.sqrt(variance))



def simulate_frame(
    spot: SpotConfig,
    camera: CameraConfig,
    background: BackgroundConfig,
    sensor_maps: SensorMaps,
    rng: np.random.Generator,
    path_xy: NDArray[np.float64] | None = None,
    extra_spots: tuple[SpotConfig, ...] = (),
) -> SimulatedFrame:
    """
    Run the image-generation pipeline and retain ground truth.

    `extra_spots` are other light sources in the frame that are not the
    tracked spot (a reflection, a second beam). Their light is added to the
    background, so `expected_background_e` and the nominal SNR count it as
    light that hides the spot, not as signal. Empty by default.

    With `path_xy` (spot centres at equally spaced instants inside the
    exposure, shape (n, 2)) the spot moves during the exposure and
    `spot.center_xy` is ignored. The true centre reported for the frame is
    then the mean position over the exposure, which is what an image formed
    by integrating light can tell you about.
    """
    validate_config(camera, spot, background)

    # Generate the center of the spot in sub-pixel coordinates
    if path_xy is None:
        spot_e = render_pixel_integrated_gaussian(camera.shape, spot)
    else:
        path_xy = np.asarray(path_xy, dtype=np.float64)
        spot_e = render_moving_spot(camera.shape, spot, path_xy)
        spot = replace(spot, center_xy=tuple(float(c) for c in path_xy.mean(axis=0)))

    # Generate the packground electrons
    background_e = render_background(camera.shape, background)
    for other in extra_spots:
        background_e = background_e + render_pixel_integrated_gaussian(camera.shape, other)

    # Apply the sentsitivity map to the spot (PRNU)
    spot_e = apply_pixel_sensitivity(spot_e, sensor_maps)
    # Apply the sensitivity map to the background light
    background_e = apply_pixel_sensitivity(background_e, sensor_maps)
    # Calculate the expected electrons from dark currents
    dark_e = expected_dark_electrons(camera, sensor_maps)

    # Sum up the collected electrons over the spot and dark noise
    collected_e = sample_poisson_electrons(
        spot_e + background_e + dark_e, rng
    )
    # Apply full well limit of pixels
    collected_e = apply_full_well_limit(collected_e, camera)
    # Count saturated pixels
    n_saturated = int(np.count_nonzero(collected_e >= camera.full_well_e))
    # Add read noise to pixels
    measured_e = add_read_noise(collected_e, camera, rng)
    # Convert signal to digital numbers
    image_dn = digitize(measured_e, camera)

    return SimulatedFrame(
        image_dn=image_dn,
        expected_spot_e=spot_e,
        expected_background_e=background_e,
        expected_dark_e=dark_e,
        true_center_xy_px=spot.center_xy,
        nominal_snr=calculate_nominal_snr(
            spot_e, background_e, dark_e, camera.read_noise_e, spot
        ),
        n_saturated_pixels=n_saturated,
    )


def signal_for_target_snr(
    target_snr: float,
    spot: SpotConfig,
    camera: CameraConfig,
    background: BackgroundConfig,
    sensor_maps: SensorMaps,
) -> float:
    """
    Return the expected total spot electrons giving the requested nominal SNR.

    Let R be the target SNR, S the expected spot electrons inside the
    aperture, and K the noise variance from background, dark current and
    read noise inside that aperture:

        K = B + D + N * read_noise_e**2
        R = S / sqrt(S + K)

    Rearranging gives S**2 - R**2 * S - R**2 * K = 0. Taking the
    nonnegative root gives the required expected electrons in the aperture:

        S = (R**2 + sqrt(R**4 + 4 * R**2 * K)) / 2

    Render a reference spot with total_signal_e=1 and apply pixel
    sensitivity. If f is its sum inside the aperture, the required total
    spot signal before pixel sensitivity is:

        total_signal_e = S / f

    Here B and D are expected background and dark electrons, and N is the
    number of aperture pixels. The reference image accounts for the spot
    shape, position, and pixel sensitivities without changing the input spot.
    Expected images are used, not noisy samples. A setting that would
    approach saturation raises a warning.
    """

    # Calculate unit expected electrons per pixel
    unit_spot = apply_pixel_sensitivity(
        render_pixel_integrated_gaussian(camera.shape, replace(spot, total_signal_e=1.0)),
        sensor_maps,
    )
    background_e = apply_pixel_sensitivity(
        render_background(camera.shape, background), sensor_maps
    )
    dark_e = expected_dark_electrons(camera, sensor_maps)

    ys, xs = np.indices(camera.shape)
    x0, y0 = spot.center_xy
    aperture = (
        ((xs - x0) / (2 * spot.sigma_x)) ** 2
        + ((ys - y0) / (2 * spot.sigma_y)) ** 2
    ) <= 1.0

    # Fraction of singal in aperture
    fraction_in_aperture = unit_spot[aperture].sum()
    k = (
        background_e[aperture].sum()
        + dark_e[aperture].sum()
        + aperture.sum() * camera.read_noise_e**2
    )

    snr2 = target_snr**2
    signal_in_aperture = (snr2 + np.sqrt(snr2**2 + 4 * snr2 * k)) / 2
    total_signal_e = signal_in_aperture / fraction_in_aperture

    peak_e = total_signal_e * unit_spot.max() + background_e.max()
    if peak_e > 0.8 * camera.full_well_e:
        warnings.warn(f"SNR {target_snr}: peak pixel near saturation ({peak_e:.0f} e)")

    return float(total_signal_e)
